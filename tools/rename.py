#!/usr/bin/env python3
"""Rename identifiers across sources, symbol map, tools and docs from CSV lists.

    python3 tools/rename.py renames/*.csv            # dry run: plan, collisions, per-file counts
    python3 tools/rename.py --apply renames/*.csv    # rewrite the tree
    python3 tools/rename.py --apply --format FILE.csv       # ... and clang-format the touched sources

Each input CSV has a header with at least the columns `old` and `new` (other
columns, such as `evidence`, are kept for the reader). A row with an empty
`new` renames nothing; it records a reviewed and rejected suggestion and only
removes the row from the worklists below.

What is rewritten:

  src/      C/C++ sources and headers. Identifiers are matched on word
            boundaries in code and comments. String and character literals are
            never changed (section names such as ".bss$Name" and text that ends
            up in the image), but an old name inside one is reported.
  other     tracked text files outside src/ (config/*.csv and *.json, tools,
            docs, README.md, ...): the old name with its linker decorations,
            so `_Old`, `_Old@8`, `@Old@8`, `?Old@@3HA` and `__imp__Old` become
            the new spelling with the same decoration.

Not rewritten: matching.json (generated by tools/match.py --update), the
rename lists themselves (renames/), vendored and generated trees.

Worklists: config/sibling-names.csv lists original-name suggestions keyed by
our name (`our_name`). Every row whose `our_name` is an old name of the input
(renamed or rejected) is removed, so the file keeps only open suggestions.

The rename is refused, before anything is written, when:

  - an old or new name is not a C identifier, or a new name is a keyword;
  - two rows rename the same old name, two old names get the same new name, or
    a new name is also an old name of the input (chains are not resolved);
  - a new name already occurs in src/ (as an identifier, macro, member, type,
    local, a separate declaration, or inside a string literal), or in its
    decorated form in config/symbols.csv. A declaration of the new name is not
    removed: VC8's code generation depends on the number of declarations, so
    dropping one is not neutral. The only exception is an alias macro
    `#define NEW OLD`, which is deleted (macros declare nothing);
  - an old name is used as a member (`.old` or `->old`), which a rename of a
    global or function must not touch;
  - an old name occurs nowhere.

The result is codegen-neutral by construction only when the old names are
global symbols; the object comparison of the gate still has to prove it.
"""
import argparse
import collections
import csv
import io
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
IDENT = re.compile(r"[A-Za-z_][A-Za-z0-9_]*\Z")
SOURCE_SUFFIXES = {".c", ".cpp", ".h", ".inc"}
TEXT_SUFFIXES = {".md", ".py", ".csv", ".json", ".yml", ".txt", ".sh"}
SKIP_FILES = {"matching.json"}
SKIP_PREFIXES = ("renames/", "lib/", "res/", "build/")
WORKLISTS = {"config/sibling-names.csv": "our_name"}
KEYWORDS = set("""
auto break case char const continue default do double else enum extern float for goto if inline int long
register restrict return short signed sizeof static struct switch typedef union unsigned void volatile while
asm bool catch class const_cast delete dynamic_cast explicit export false friend mutable namespace new operator
private protected public reinterpret_cast static_cast template this throw true try typeid typename using virtual
wchar_t
""".split())
# C/C++ lexer: comments, string and character literals; everything else is code.
ALIAS = re.compile(r"[ \t]*#[ \t]*define[ \t]+([A-Za-z_]\w*)[ \t]+([A-Za-z_]\w*)[ \t]*(?://[^\n]*)?\n?\Z")
LEXER = re.compile(r'//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\\n])*"|\'(?:\\.|[^\'\\\n])*\'', re.S)


class RenameError(ValueError):
    pass


def load_pairs(paths):
    """Return ({old: new or ''}, {new: reason}) from the CSV files.

    The optional `allow` column names why existing occurrences of the new name
    are fine (for example struct members of the same name); it is checked by hand.
    """
    pairs, allow = {}, {}
    for path in paths:
        text = Path(path).read_text(encoding="utf-8")
        reader = csv.DictReader(io.StringIO(text))
        if not reader.fieldnames or "old" not in reader.fieldnames or "new" not in reader.fieldnames:
            raise RenameError(f"{path}: needs a header with the columns old,new")
        for number, row in enumerate(reader, 2):
            old, new = (row["old"] or "").strip(), (row["new"] or "").strip()
            if not old:
                continue
            if old in pairs:
                raise RenameError(f"{path}:{number}: {old} is listed twice")
            pairs[old] = new
            if new and (row.get("allow") or "").strip():
                allow[new] = row["allow"].strip()
    return pairs, allow


def validate_pairs(pairs):
    errors = []
    targets = collections.defaultdict(list)
    for old, new in pairs.items():
        if not IDENT.match(old):
            errors.append(f"old name {old!r} is not an identifier")
        if not new:
            continue
        if not IDENT.match(new):
            errors.append(f"new name {new!r} is not an identifier")
        if new in KEYWORDS:
            errors.append(f"new name {new!r} is a keyword")
        if new == old:
            errors.append(f"{old} is renamed to itself")
        if new in pairs:
            errors.append(f"{old} -> {new}: {new} is itself an old name (no chains)")
        targets[new].append(old)
    for new, olds in targets.items():
        if len(olds) > 1:
            errors.append(f"{', '.join(sorted(olds))} all become {new}")
    return errors


def tracked_files(root):
    """Tracked files when root is a git checkout's top level, else every file under root."""
    root = Path(root).resolve()
    try:
        top = subprocess.run(["git", "rev-parse", "--show-toplevel"], cwd=root, check=True,
                             capture_output=True, text=True).stdout.strip()
        if Path(top).resolve() != root:
            raise ValueError(top)
        output = subprocess.run(["git", "ls-files", "-z"], cwd=root, check=True,
                                capture_output=True).stdout.decode("utf-8")
        names = [name for name in output.split("\0") if name]
    except (OSError, ValueError, subprocess.CalledProcessError):
        names = [p.relative_to(root).as_posix() for p in root.rglob("*") if p.is_file()]
    return sorted(name for name in names if (root / name).is_file())


def classify(root):
    sources, texts = [], []
    for name in tracked_files(root):
        if name in SKIP_FILES or name.startswith(SKIP_PREFIXES) or "/__pycache__/" in name:
            continue
        suffix = Path(name).suffix
        if name.startswith("src/") and suffix in SOURCE_SUFFIXES:
            sources.append(name)
        elif not name.startswith("src/") and (suffix in TEXT_SUFFIXES or Path(name).name == "Makefile"):
            texts.append(name)
    return sources, texts


def split_source(text):
    """Yield (kind, chunk) with kind 'code', 'comment' or 'string'; joining the chunks gives text back."""
    last = 0
    for match in LEXER.finditer(text):
        if match.start() > last:
            yield "code", text[last:match.start()]
        token = match.group()
        yield ("comment" if token[0] == "/" else "string"), token
        last = match.end()
    if last < len(text):
        yield "code", text[last:]


def word_pattern(names):
    names = sorted(names, key=len, reverse=True)
    return re.compile(r"(?<![A-Za-z0-9_])(" + "|".join(map(re.escape, names)) + r")(?![A-Za-z0-9_])")


def decorated_pattern(names):
    # A decorated occurrence: preceded by a non-identifier character, optionally
    # through leading underscores or __imp_ (C linker names), and not followed by
    # an identifier character.
    names = sorted(names, key=len, reverse=True)
    return re.compile(r"(?:(?<![A-Za-z0-9_])|(?<=(?<![A-Za-z0-9_])_)|(?<=(?<![A-Za-z0-9_])__)"
                      r"|(?<=(?<![A-Za-z0-9_])___)|(?<=__imp__))("
                      + "|".join(map(re.escape, names)) + r")(?![A-Za-z0-9_])")


def line_of(text, offset):
    return text.count("\n", 0, offset) + 1


class Plan:
    def __init__(self, root, pairs, allow=None):
        self.root, self.pairs = Path(root), pairs
        self.renames = {old: new for old, new in pairs.items() if new}
        self.errors = validate_pairs(pairs)
        self.warnings = []
        self.changes = {}          # relative path -> new text
        self.counts = collections.Counter()  # old -> occurrences changed
        self.string_hits = []      # (path, line, old)
        self.removed_rows = collections.defaultdict(list)
        self.allow = dict(allow or {})
        self.aliases = collections.defaultdict(list)   # new name -> removed `#define NEW OLD` lines
        if self.errors:
            return
        self.sources, self.texts = classify(self.root)
        self.scan()

    def strip_aliases(self, name, text):
        """Drop `#define NEW OLD` alias lines: after the rename they would define NEW as itself."""
        lines = text.splitlines(keepends=True)
        kept = []
        for number, line in enumerate(lines, 1):
            alias = ALIAS.match(line)
            if alias and self.renames.get(alias.group(2)) == alias.group(1):
                self.aliases[alias.group(1)].append(f"{name}:{number}")
                continue
            kept.append(line)
        return "".join(kept)

    def scan(self):
        olds, news = set(self.renames), set(self.renames.values())
        old_re = word_pattern(olds) if olds else None
        new_re = word_pattern(news) if news else None
        seen_old = set()
        clashes = collections.defaultdict(list)    # new name -> [(path, line, where)]
        texts = {}
        for name in self.sources:
            original = (self.root / name).read_text(encoding="latin-1")
            texts[name] = (original, self.strip_aliases(name, original))
        for name, (original, text) in texts.items():
            out = []
            offset = 0
            for kind, chunk in split_source(text):
                start, offset = offset, offset + len(chunk)
                if new_re and kind != "comment":
                    for match in new_re.finditer(chunk):
                        where = "a string literal" if kind == "string" else "code"
                        clashes[match.group(1)].append((name, line_of(text, start + match.start()), where))
                if old_re and kind == "string":
                    for match in old_re.finditer(chunk):
                        seen_old.add(match.group(1))
                        self.string_hits.append((name, line_of(text, start + match.start()), match.group(1)))
                if old_re and kind in ("code", "comment"):
                    if kind == "code":
                        for match in old_re.finditer(chunk):
                            before = chunk[:match.start()].rstrip()
                            if before.endswith((".", "->")) and not before.endswith(".."):
                                self.errors.append(f"{name}:{line_of(text, start + match.start())}: "
                                                   f"{match.group(1)} is used as a member")

                    def replace(match):
                        self.counts[match.group(1)] += 1
                        seen_old.add(match.group(1))
                        return self.renames[match.group(1)]
                    chunk = old_re.sub(replace, chunk)
                out.append(chunk)
            result = "".join(out)
            if result != original:
                self.changes[name] = result
        for new, hits in sorted(clashes.items()):
            if new in self.aliases:
                continue    # the alias macro made these uses of the renamed symbol already
            if new in self.allow:
                self.warnings.append(f"{new}: {len(hits)} existing occurrences allowed ({self.allow[new]})")
                continue
            for path, line, where in hits:
                self.errors.append(f"{path}:{line}: new name {new} already occurs in {where}")
        self.scan_texts(olds, news, seen_old)
        for old in sorted(set(self.pairs) - seen_old - set(self.removed_rows_olds())):
            self.errors.append(f"{old} occurs nowhere")

    def removed_rows_olds(self):
        return {old for rows in self.removed_rows.values() for old in rows}

    def scan_texts(self, olds, news, seen_old):
        old_re = decorated_pattern(olds) if olds else None
        symbols = self.root / "config/symbols.csv"
        if news and symbols.is_file():
            text = symbols.read_text(encoding="utf-8")
            for match in decorated_pattern(news).finditer(text):
                self.errors.append(f"config/symbols.csv:{line_of(text, match.start())}: "
                                   f"new name {match.group(1)} is already mapped")
        for name in self.texts:
            path = self.root / name
            text = path.read_text(encoding="utf-8", errors="surrogateescape")
            if name in WORKLISTS:
                text = self.prune_worklist(name, text)
            new_text = text
            if old_re:
                def replace(match):
                    self.counts[match.group(1)] += 1
                    seen_old.add(match.group(1))
                    return self.renames[match.group(1)]
                new_text = old_re.sub(replace, text)
            if new_text != path.read_text(encoding="utf-8", errors="surrogateescape"):
                self.changes[name] = new_text

    def prune_worklist(self, name, text):
        column = WORKLISTS[name]
        lines = text.splitlines(keepends=True)
        if not lines:
            return text
        header = next(csv.reader([lines[0]]))
        if column not in header:
            raise RenameError(f"{name}: worklist column {column} missing")
        index = header.index(column)
        kept = [lines[0]]
        for line in lines[1:]:
            fields = next(csv.reader([line]), [])
            if len(fields) > index and fields[index] in self.pairs:
                self.removed_rows[name].append(fields[index])
            else:
                kept.append(line)
        return "".join(kept)

    def report(self, out=sys.stdout):
        renamed = len(self.renames)
        rejected = len(self.pairs) - renamed
        print(f"{renamed} renames, {rejected} rejected rows; {len(self.changes)} files change; "
              f"{sum(self.counts.values())} occurrences", file=out)
        for name in sorted(self.changes):
            print(f"  {name}", file=out)
        for new, where in sorted(self.aliases.items()):
            print(f"alias macro removed: #define {new} ... at {', '.join(where)}", file=out)
        for name, olds in sorted(self.removed_rows.items()):
            print(f"worklist {name}: {len(olds)} rows removed", file=out)
        if self.string_hits:
            print(f"{len(self.string_hits)} old names inside string literals (kept):", file=out)
            for path, line, old in self.string_hits:
                print(f"  {path}:{line}: {old}", file=out)
        for warning in self.warnings:
            print(f"warning: {warning}", file=out)
        for error in self.errors:
            print(f"error: {error}", file=out)

    def apply(self):
        if self.errors:
            raise RenameError(f"{len(self.errors)} errors; nothing written")
        for name, text in self.changes.items():
            path = self.root / name
            encoding = "latin-1" if name.startswith("src/") else "utf-8"
            errors = "strict" if encoding == "latin-1" else "surrogateescape"
            with open(path, "w", encoding=encoding, errors=errors, newline="") as handle:
                handle.write(text)
        return sorted(self.changes)


def clang_format(root, names):
    tool = shutil.which("clang-format-18") or shutil.which("clang-format")
    if tool is None:
        raise RenameError("clang-format 18 is required for --format")
    files = [name for name in names if name.startswith("src/") and Path(name).suffix in SOURCE_SUFFIXES]
    for start in range(0, len(files), 100):
        subprocess.run([tool, "-i", "--style=file", *files[start:start + 100]], cwd=root, check=True)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("csv", nargs="+", help="rename lists with old,new columns")
    parser.add_argument("--apply", action="store_true", help="rewrite the files (default: dry run)")
    parser.add_argument("--format", action="store_true", help="with --apply: clang-format the touched sources")
    parser.add_argument("--root", default=str(ROOT), help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    root = Path(args.root)
    try:
        pairs, allow = load_pairs(args.csv)
        plan = Plan(root, pairs, allow)
        plan.report()
        if plan.errors:
            return 1
        if args.apply:
            names = plan.apply()
            if args.format:
                clang_format(root, names)
            print(f"applied: {len(names)} files written")
    except RenameError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
